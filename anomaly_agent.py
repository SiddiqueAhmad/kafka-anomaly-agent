def get_readonly_conn():
    """Connection used to run LLM-generated SQL — read-only at the session level
    so an injected/hallucinated statement physically cannot mutate data."""
    conn = psycopg2.connect(**DB_CONFIG)
    conn.set_session(readonly=True, autocommit=True)
    return conn


# Statements the LLM is allowed to run. Anything else is rejected before execution.
_FORBIDDEN_SQL = re.compile(
    r"\b(INSERT|UPDATE|DELETE|DROP|ALTER|TRUNCATE|CREATE|GRANT|REVOKE|"
    r"COPY|MERGE|CALL|DO|VACUUM|EXECUTE)\b",
    re.IGNORECASE,
)


def is_safe_select(sql: str) -> bool:
    """Allow exactly one read-only SELECT (or WITH ... SELECT) statement."""
    stripped = sql.strip().rstrip(";").strip()
    if not stripped:
        return False
    # reject multiple statements (defends against `SELECT 1; DROP TABLE ...`)
    if ";" in stripped:
        return False
    if not re.match(r"^(SELECT|WITH)\b", stripped, re.IGNORECASE):
        return False
    if _FORBIDDEN_SQL.search(stripped):
        return False
    return True

