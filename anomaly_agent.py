graph.add_node("report_generator", report_generator_node)
graph.add_node("alert_dispatcher", alert_dispatcher_node)
graph.add_node("rag_context",rag_context_node)

graph.set_entry_point("supervisor")

graph.add_conditional_edges(
    "supervisor",
    route_on_anomalies,
    {
        "investigate": "baseline",
        "wait":        END,
    }
)
graph.add_edge("baseline",         "nl_to_sql")
graph.add_edge("nl_to_sql",        "rag_context")
graph.add_edge("rag_context",        "report_generator")
graph.add_edge("report_generator", "alert_dispatcher")
graph.add_edge("alert_dispatcher", END)

app = graph.compile()


